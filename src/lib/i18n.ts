export type Locale = "en" | "es";

const COOKIE = "sl_lang";

export function detectLocale(
  cookie?: string | null,
  accept?: string | null,
  navigatorLang?: string | null,
): Locale {
  if (cookie === "en" || cookie === "es") return cookie;
  const first =
    (navigatorLang || "")
      .split(",")[0]
      ?.trim()
      .split(";")[0]
      .toLowerCase() ||
    (accept || "")
      .split(",")[0]
      ?.trim()
      .split(";")[0]
      .toLowerCase() ||
    "en";
  return first.startsWith("es") ? "es" : "en";
}

export function langCookieName() {
  return COOKIE;
}

